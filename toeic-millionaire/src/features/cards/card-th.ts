export function getCardCopy(
  id: string,
  title: string,
  body: string,
  isTh: boolean,
): { title: string; body: string } {
  if (!isTh) return { title, body };
  const th = cardTh[id];
  return {
    title: th?.titleTh ?? title,
    body: th?.bodyTh ?? body,
  };
}
